#!/usr/bin/env python3
"""Convert one MIDI track to a compact monophonic frequency timeline."""

import argparse
import base64
import struct
from bisect import bisect_right
from collections import defaultdict
from pathlib import Path

import mido


def tempo_map(mid):
    events = []
    for track in mid.tracks:
        tick = 0
        for msg in track:
            tick += msg.time
            if msg.type == "set_tempo":
                events.append((tick, msg.tempo))
    events.sort()
    if not events or events[0][0] != 0:
        events.insert(0, (0, 500_000))

    ticks = []
    seconds = []
    tempo = events[0][1]
    last_tick = 0
    elapsed = 0.0
    for tick, new_tempo in events:
        if tick > last_tick:
            elapsed += mido.tick2second(
                tick - last_tick, mid.ticks_per_beat, tempo
            )
        ticks.append(tick)
        seconds.append(elapsed)
        last_tick = tick
        tempo = new_tempo

    def to_seconds(tick):
        index = bisect_right(ticks, tick) - 1
        return seconds[index] + mido.tick2second(
            tick - ticks[index], mid.ticks_per_beat, tempo_events[index]
        )

    tempo_events = [value for _, value in events]
    return to_seconds


def track_notes(track):
    active = defaultdict(list)
    notes = []
    tick = 0
    for msg in track:
        tick += msg.time
        if msg.type == "note_on" and msg.velocity > 0:
            active[(msg.channel, msg.note)].append(tick)
        elif msg.type == "note_off" or (
            msg.type == "note_on" and msg.velocity == 0
        ):
            key = (msg.channel, msg.note)
            if active[key]:
                start = active[key].pop(0)
                if tick > start:
                    notes.append((start, tick, msg.note))

    for (channel, note), starts in active.items():
        del channel
        for start in starts:
            if tick > start:
                notes.append((start, tick, note))
    return notes


def polyphonic_segments(notes, max_voices=3):
    boundaries = sorted({value for start, end, _ in notes for value in (start, end)})
    segments = []
    for start, end in zip(boundaries, boundaries[1:]):
        pitches = sorted(
            {
                note
                for note_start, note_end, note in notes
                if note_start < end and note_end > start
            }
        )
        if pitches:
            chord = tuple(pitches[-max_voices:])
            if segments and segments[-1][2] == chord and segments[-1][1] == start:
                segments[-1] = (segments[-1][0], end, chord)
            else:
                segments.append((start, end, chord))
    return segments


def frequency(note):
    return int(round(440.0 * (2.0 ** ((note - 69) / 12.0))))


def timeline_records(segments, to_seconds):
    records = []
    previous_end = None
    for start_tick, end_tick, notes in segments:
        start_ms = int(round(to_seconds(start_tick) * 1000))
        end_ms = max(start_ms + 1, int(round(to_seconds(end_tick) * 1000)))
        if previous_end is None:
            previous_end = start_ms
        if start_ms > previous_end:
            records.append(((0, 0, 0), start_ms - previous_end))
        records.append((tuple(frequency(note) for note in notes), end_ms - start_ms))
        previous_end = end_ms
    return records


def write_module(path, title, track_index, records):
    payload = b"".join(
        struct.pack(
            ">HHHH",
            frequencies[0] if len(frequencies) > 0 else 0,
            frequencies[1] if len(frequencies) > 1 else 0,
            frequencies[2] if len(frequencies) > 2 else 0,
            duration_ms,
        )
        for frequencies, duration_ms in records
    )
    encoded = base64.b64encode(payload).decode("ascii")
    lines = [
        "# Generated by midi_preprocess.py; do not edit by hand.",
        "TITLE = {!r}".format(title),
        "TRACK_INDEX = {}".format(track_index),
        "SAMPLE_RATE = 22050",
        "DATA_B64 = (",
    ]
    lines.extend('    "{}"'.format(encoded[i:i + 76])
                 for i in range(0, len(encoded), 76))
    lines.append(")")
    with open(path, "w", encoding="ascii") as output:
        output.write("\n".join(lines))
        output.write("\n")
    return payload


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("midi")
    parser.add_argument(
        "--track",
        type=int,
        help="MIDI track index; default is the track with most notes",
    )
    parser.add_argument(
        "--output",
        default="midi_song.py",
        help="generated MicroPython module",
    )
    args = parser.parse_args()

    midi = mido.MidiFile(args.midi)
    all_notes = [track_notes(track) for track in midi.tracks]
    if args.track is None:
        track_index = max(range(len(all_notes)), key=lambda index: len(all_notes[index]))
    else:
        track_index = args.track
    notes = all_notes[track_index]
    if not notes:
        raise SystemExit("selected track has no notes")

    segments = polyphonic_segments(notes, max_voices=3)
    records = timeline_records(segments, tempo_map(midi))
    title = Path(args.midi).stem
    payload = write_module(args.output, title, track_index, records)
    duration_ms = sum(duration for _, duration in records)
    frequency_notes = sum(1 for frequencies, _ in records if any(frequencies))
    max_voices = max(len(notes) for _, _, notes in segments)
    print("input:", args.midi)
    print("selected_track:", track_index, "source_notes:", len(notes))
    print("polyphonic_segments:", len(segments), "max_voices:", max_voices)
    print("output_records:", len(records), "notes:", frequency_notes)
    print("duration_seconds:", round(duration_ms / 1000.0, 2))
    print("payload_bytes:", len(payload))
    print("output:", args.output)


if __name__ == "__main__":
    main()
